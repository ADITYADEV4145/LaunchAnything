import { createHash, randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { packageRoot } from '../core/package-root.js';

export interface Product { id: string; name: string; repo: string; category: string; channels: ('show-hn' | 'x')[] }
interface Pair { id: string; product: string; channel: string; a: 'plain' | 'liftoff'; sourceHashes: string[]; hashes: string[] }
interface Key { seed: string; pairs: Pair[] }
export interface Vote { voterId: string; pair: string; click: 'A' | 'B' | 'tie'; trust: 'A' | 'B' | 'tie'; missing: { A: string; B: string } }
export interface BenchOptions { run?: string; product?: string; seed?: string }
const hash = (value: string) => createHash('sha256').update(value).digest('hex');
const safeId = (value: string) => /^[a-z0-9][a-z0-9-]{0,100}$/.test(value);
const root = (cwd: string) => join(cwd, 'bench/runs');
const questions = ['Which would you click?', 'Which do you trust more?', "What's missing from each?"];
export async function products(): Promise<Product[]> {
  return JSON.parse(await readFile(join(packageRoot(), 'bench/launchbench/products.json'), 'utf8'));
}
async function optional(path: string) {
  try { return await readFile(path, 'utf8'); } catch (e) { if ((e as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw e; }
}
async function current(cwd: string, run?: string) {
  if (run) { if (!safeId(run)) throw new Error('Invalid benchmark run ID'); return run; }
  try { return (await readdir(root(cwd), { withFileTypes: true })).filter(e => e.isDirectory() && safeId(e.name)).map(e => e.name).sort().at(-1); }
  catch (e) { if ((e as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw e; }
}
async function runPath(cwd: string, run?: string) {
  const id = await current(cwd, run);
  if (!id) throw new Error('No benchmark run; run liftoff bench prepare first');
  const path = join(root(cwd), id); await stat(path);
  return { id, path };
}
async function once(path: string, content: string, mode = 0o644) {
  try { await writeFile(path, content, { flag: 'wx', mode }); } catch (e) { if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e; }
}
export async function prepare(cwd: string, options: BenchOptions = {}) {
  const catalog = await products();
  const selected = options.product ? catalog.filter(p => p.id === options.product) : catalog;
  if (!selected.length) throw new Error('Unknown benchmark product');
  const run = options.run ?? `${Date.now()}-${randomBytes(4).toString('hex')}`;
  if (!safeId(run)) throw new Error('Invalid benchmark run ID');
  const path = join(root(cwd), run); await mkdir(path, { recursive: true });
  for (const product of selected) {
    const dir = join(path, product.id); await mkdir(dir, { recursive: true });
    await once(join(dir, 'product.json'), JSON.stringify(product, null, 2) + '\n');
    await once(join(dir, 'plain-prompt.txt'), 'Write a Show HN post and an X thread for this repo.');
    await once(join(dir, 'instructions.md'), `# ${product.name}\n\nRepository: ${product.repo}\n\nAgent task; the CLI does not fetch repositories or call an LLM.\n\n1. Obtain this public repository separately. Save the exact README as README.md here and record its commit SHA and model/version in provenance.md. Do not invent product facts.\n2. In an isolated model context given ONLY that README, submit plain-prompt.txt verbatim. Save the response as plain.md. Do not expose Liftoff rules, drafts or product metadata to that baseline context.\n3. In a separate context on the same repository revision, run the normal Liftoff pipeline: init → scan → agent writes product.json → validate → plan → brief → write → agent writes posts → check. Explicitly select show-hn and x in config. Save the resulting posts in liftoff.md. Do not publish. Record commands, revisions, model/version and any edits in provenance.md.\n4. Both files must contain exactly one level-two heading for each channel: "## show-hn" and "## x". Keep all post content underneath these headings (use other heading levels inside). Do not label either method inside the post content. Do not copy one version into the other or claim human preference.\n5. Run bench pair --run ${run}, then distribute ONLY the blind/ folder to independent human voters. Never distribute private-key.json, source drafts, prompts or provenance before voting closes.\n\nNo votes or results are generated by prepare.\n`);
  }
  return { run, path, products: selected.map(p => p.id), instruction: 'Agent must provide README, provenance, plain.md and liftoff.md; no LLM or network calls were made.' };
}
function sections(source: string) {
  const headings = [...source.matchAll(/^## (.+)\r?$/gm)];
  if (headings.length !== 2 || headings.filter(h => h[1] === 'show-hn').length !== 1 || headings.filter(h => h[1] === 'x').length !== 1) throw new Error('Drafts require exactly one ## show-hn and one ## x heading');
  return Object.fromEntries(headings.map((heading, i) => {
    const body = source.slice(heading.index! + heading[0].length, headings[i + 1]?.index ?? source.length).trim();
    if (!body) throw new Error('Benchmark post cannot be empty');
    return [heading[1], body + '\n'];
  }));
}
export async function pair(cwd: string, options: BenchOptions = {}) {
  if (options.product && !(await products()).some(p => p.id === options.product)) throw new Error('Unknown benchmark product');
  const { id: run, path } = await runPath(cwd, options.run);
  const saved = await optional(join(path, 'private-key.json'));
  const key: Key = saved ? JSON.parse(saved) : { seed: options.seed ?? randomBytes(32).toString('hex'), pairs: [] };
  if (saved && options.seed !== undefined && key.seed !== options.seed) throw new Error('Run already has a different pairing seed');
  const pending: string[] = [];
  for (const product of await products()) {
    if (options.product && product.id !== options.product) continue;
    const dir = join(path, product.id), plain = await optional(join(dir, 'plain.md')), liftoff = await optional(join(dir, 'liftoff.md'));
    if (plain === undefined || liftoff === undefined) { pending.push(product.id); continue; }
    const bodies = { plain: sections(plain), liftoff: sections(liftoff) };
    for (const channel of product.channels) {
      const id = `${product.id}:${channel}`, sourceHashes = [hash(bodies.plain[channel]), hash(bodies.liftoff[channel])];
      const prior = key.pairs.find(p => p.id === id);
      if (prior) { if (JSON.stringify(prior.sourceHashes) !== JSON.stringify(sourceHashes)) throw new Error('Paired drafts changed; create a new run'); continue; }
      const a = parseInt(hash(`${key.seed}:${id}`).slice(0, 8), 16) % 2 === 0 ? 'plain' : 'liftoff';
      const texts = [bodies[a][channel], bodies[a === 'plain' ? 'liftoff' : 'plain'][channel]];
      const target = join(path, 'blind', product.id, channel); await mkdir(target, { recursive: true });
      await writeFile(join(target, 'A.md'), texts[0]); await writeFile(join(target, 'B.md'), texts[1]);
      key.pairs.push({ id, product: product.id, channel, a, sourceHashes, hashes: texts.map(hash) });
    }
  }
  await writeFile(join(path, 'private-key.json'), JSON.stringify(key, null, 2) + '\n', { mode: 0o600 });
  await mkdir(join(path, 'blind'), { recursive: true });
  await writeFile(join(path, 'blind/ballot-template.json'), JSON.stringify({ questions, votes: key.pairs.map(p => ({ voterId: '', pair: p.id, click: null, trust: null, missing: { A: '', B: '' } })) }, null, 2) + '\n');
  return { run, paired: key.pairs.length, pending, ballot: join(path, 'blind/ballot-template.json'), instruction: 'Share only blind/. Keep private-key.json private. No votes have been generated.' };
}
async function checkedKey(path: string): Promise<Key> {
  const source = await optional(join(path, 'private-key.json'));
  const key: Key = source ? JSON.parse(source) : { seed: '', pairs: [] };
  for (const pair of key.pairs) {
    for (const [i, label] of ['A', 'B'].entries()) {
      if (hash(await readFile(join(path, 'blind', pair.product, pair.channel, label + '.md'), 'utf8')) !== pair.hashes[i]) throw new Error('Blind pair changed; do not score altered ballots');
    }
  }
  return key;
}
function validateVotes(value: unknown, pairs: Pair[]): Vote[] {
  if (!value || typeof value !== 'object' || !Array.isArray((value as { votes?: unknown }).votes)) throw new Error('Votes file must contain a votes array');
  const votes = (value as { votes: Vote[] }).votes, seen = new Set<string>();
  for (const vote of votes) {
    if (!vote || typeof vote.voterId !== 'string' || !/^[\w.-]{1,100}$/.test(vote.voterId) || !pairs.some(p => p.id === vote.pair) || !['A', 'B', 'tie'].includes(vote.click) || !['A', 'B', 'tie'].includes(vote.trust) || !vote.missing || typeof vote.missing.A !== 'string' || typeof vote.missing.B !== 'string') throw new Error('Invalid vote: require voterId, known pair, click/trust A|B|tie and missing.A/B text');
    const id = `${vote.voterId}:${vote.pair}`;
    if (seen.has(id)) throw new Error('Duplicate voter/pair vote');
    seen.add(id);
  }
  return votes.map(v => ({ voterId: v.voterId, pair: v.pair, click: v.click, trust: v.trust, missing: { A: v.missing.A, B: v.missing.B } }));
}
export async function record(cwd: string, file: string, options: BenchOptions = {}) {
  const { id: run, path } = await runPath(cwd, options.run), key = await checkedKey(path);
  const incoming = validateVotes(JSON.parse(await readFile(file, 'utf8')), key.pairs);
  const previous = JSON.parse(await optional(join(path, 'votes.json')) ?? '{"votes":[]}');
  const votes = validateVotes({ votes: [...validateVotes(previous, key.pairs), ...incoming] }, key.pairs);
  await writeFile(join(path, 'votes.json'), JSON.stringify({ votes }, null, 2) + '\n', { mode: 0o600 });
  return { run, recorded: incoming.length, total: votes.length, note: 'Imported votes only; CLI cannot verify voter identity or independence.' };
}
export function wilson(wins: number, total: number) {
  if (!total) return null;
  const z = 1.959963984540054, p = wins / total, d = 1 + z * z / total;
  const center = (p + z * z / (2 * total)) / d, margin = z * Math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / d;
  return { low: Math.max(0, center - margin), high: Math.min(1, center + margin) };
}
export async function score(cwd: string, options: BenchOptions = {}) {
  const run = await current(cwd, options.run);
  const path = run ? join(root(cwd), run) : undefined;
  if (options.run && path) await stat(path);
  const key = path ? await checkedKey(path) : { seed: '', pairs: [] };
  const votes = path ? validateVotes(JSON.parse(await optional(join(path, 'votes.json')) ?? '{"votes":[]}'), key.pairs) : [];
  const summarize = (selected: Vote[], question: 'click' | 'trust' = 'click') => {
    const decisive = selected.filter(v => v[question] !== 'tie');
    const wins = decisive.filter(v => (v[question] === 'A') === (key.pairs.find(p => p.id === v.pair)!.a === 'liftoff')).length;
    return { measured: decisive.length > 0, voteCount: selected.length, decisiveVotes: decisive.length, ties: selected.length - decisive.length, liftoffWins: wins, winRate: decisive.length ? wins / decisive.length : null, wilson95: wilson(wins, decisive.length) };
  };
  const overall = summarize(votes);
  return { run: run ?? null, ...overall, productsCovered: new Set(votes.map(v => key.pairs.find(p => p.id === v.pair)!.product)).size,
    perChannel: Object.fromEntries(['show-hn', 'x'].map(channel => [channel, summarize(votes.filter(v => key.pairs.find(p => p.id === v.pair)!.channel === channel))])),
    trust: summarize(votes, 'trust'), metric: 'Click preference among decisive human ballots; ties excluded from win-rate denominator. Votes are self-reported, not verified identities. Wilson intervals treat ballots as independent; repeated voters/products may be correlated.',
    message: overall.measured ? 'Calculated from imported ballots; organizer must verify human participation and provenance.' : 'Win rate: not yet measured, pending human votes (or decisive choices).' };
}
export async function run(cwd: string, options: BenchOptions = {}) {
  const prepared = await prepare(cwd, { ...options, run: await current(cwd, options.run) });
  const paired = await pair(cwd, { ...options, run: prepared.run });
  return { prepared, paired, score: await score(cwd, { run: prepared.run }) };
}
